package OrdenacionAlumnosClase;



public class Alumno {
	
	private String nombre;
	
	private double nota;
	

	
	public void setNota(double nota){

		this.nota = nota;
}
	public double getNotas() {
		return this.nota;
	}
	
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	
	public String getNombre() {
		return this.nombre;
	}
	
}



